import { loadConfig } from '../server/src/config.js';
import { Store } from '../server/src/db/client.js';
import { ArtifactStore } from '../server/src/services/artifactStore.js';
const config = loadConfig();
const store = new Store(config.DATA_DIR);
store.tables(['audit']);
const artifacts = new ArtifactStore(store, config);
for (let i = 0; i < 200; i++)
  artifacts.ingest({
    project: ['research', 'daily', 'engineering'][i % 3],
    kind: ['markdown', 'html', 'csv', 'log', 'json', 'diff'][i % 6],
    title: 'Sample artifact ' + (i + 1),
    summary: 'Explicit demo seed data; no live backend or personal information.',
    file:
      i % 6 === 1
        ? '<h1>Example report</h1>'
        : '# Example ' + i + '\nA small example generated by the seed script.',
    idempotency_key: 'seed:' + i,
  });
store.close();
console.log('Seeded 200 explicitly labelled demo artifacts.');
